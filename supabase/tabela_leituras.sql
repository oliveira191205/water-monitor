-- Estrutura da tabela utilizada pela API de monitoramento do reservatório.
-- Execute em um projeto Supabase novo, ou compare com a tabela existente antes de executar.

CREATE TABLE IF NOT EXISTS public.leituras (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL,
  distance_cm DOUBLE PRECISION NOT NULL,
  level_percent DOUBLE PRECISION NOT NULL
    CHECK (level_percent >= 0 AND level_percent <= 100),
  alerta BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Mantém o acesso direto à tabela protegido por RLS.
-- A Edge Function utiliza a chave de serviço no servidor para gravar e consultar.
ALTER TABLE public.leituras ENABLE ROW LEVEL SECURITY;

-- Índice para facilitar a consulta das leituras mais recentes.
CREATE INDEX IF NOT EXISTS idx_leituras_created_at
ON public.leituras (created_at DESC);
